# Функция для подготовки данных к нормализации
def prepare_for_normalization(df):
    """Подготовка данных для нормализации"""
    df_norm = df.copy()

    # Преобразуем числовые колонки
    numeric_cols = ['Прибыль компании-клиента', 'ID клиента']
    for col in numeric_cols:
        if col in df_norm.columns:
            df_norm[col] = pd.to_numeric(df_norm[col], errors='coerce')

    return df_norm

# Функция для нормализации данных
def normalize_data(df):
    """Нормализация данных (MinMaxScaler для числовых колонок)"""
    df_normalized = df.copy()

    # ID не нормализуем
    id_col = 'ID клиента'

    # Категориальные колонки для one-hot encoding
    categorical_cols = ['Тип компании', 'Постоянный или новый клиент',
                        'Стадия работы с клиентом', 'Потребность клиента в товаре']

    # One-hot encoding для категориальных переменных
    for col in categorical_cols:
        if col in df_normalized.columns:
            dummies = pd.get_dummies(df_normalized[col], prefix=col)
            df_normalized = pd.concat([df_normalized, dummies], axis=1)

    # Числовые колонки для нормализации (кроме ID)
    numeric_cols = ['Прибыль компании-клиента']
    numeric_cols_existing = [col for col in numeric_cols if col in df_normalized.columns]

    # MinMaxScaler для числовых колонок
    scaler = MinMaxScaler()
    df_normalized[numeric_cols_existing] = scaler.fit_transform(df_normalized[numeric_cols_existing])

    # Удаляем оригинальные категориальные колонки (оставляем только закодированные)
    for col in categorical_cols:
        if col in df_normalized.columns:
            df_normalized = df_normalized.drop(columns=[col])

    return df_normalized, scaler

# Функция для обучения классификатора и получения вероятностей
def train_classifier_and_predict(df):
    """Обучение классификатора и предсказание вероятностей для всех клиентов"""

    # Создаем целевую переменную: договор заключен (1) или нет (0)
    df['Договор_заключен'] = (df['Стадия работы с клиентом'] == 'Договор заключен').astype(int)

    # Признаки для модели
    categorical_cols = ['Тип компании', 'Постоянный или новый клиент',
                        'Стадия работы с клиентом', 'Потребность клиента в товаре']

    # One-hot encoding
    df_encoded = pd.get_dummies(df, columns=categorical_cols)

    # Числовые признаки
    numeric_cols = ['Прибыль компании-клиента']
    feature_cols = numeric_cols + [col for col in df_encoded.columns if col.startswith(tuple(categorical_cols))]

    # Убираем ID и целевую переменную из признаков
    feature_cols = [col for col in feature_cols if col not in ['ID клиента', 'Договор_заключен']]

    X = df_encoded[feature_cols].values
    y = df['Договор_заключен'].values

    # Нормализация признаков для модели
    scaler_X = StandardScaler()
    X_scaled = scaler_X.fit_transform(X)

    # Разделение на обучающую и тестовую выборки
    X_train, X_test, y_train, y_test = train_test_split(
        X_scaled, y, test_size=0.2, random_state=42, stratify=y
    )

    # Обучение модели
    model = RandomForestClassifier(n_estimators=100, random_state=42)
    model.fit(X_train, y_train)

    # Предсказание вероятностей для ВСЕХ клиентов
    probabilities = model.predict_proba(X_scaled)

    # Точность на тестовой выборке
    y_pred = model.predict(X_test)
    accuracy = accuracy_score(y_test, y_pred)

    return model, probabilities, accuracy, df

# Функция для записи нормализованных данных в лист
def write_normalized_to_sheet(df_normalized):
    """Запись нормализованных данных в лист 'Нормализованные клиенты'"""

    # Подготавливаем данные для записи
    headers = list(df_normalized.columns)
    values = df_normalized.values.tolist()

    # Записываем заголовки
    normalized_sheet.update('A1', [headers])

    # Записываем данные (пакетно по 100 строк для оптимизации)
    batch_size = 100
    for i in range(0, len(values), batch_size):
        batch = values[i:i+batch_size]
        normalized_sheet.update(f'A{i+2}', batch)

    print(f"✅ Записано {len(values)} строк в лист 'Нормализованные клиенты'")
    print(f"   - Столбцов: {len(headers)}")

# Функция для записи результатов в лист (только ID и вероятность)
def write_results_to_sheet(df, probabilities):
    """Запись ID клиента и вероятности заключения договора в лист 'Результаты'"""

    # Подготавливаем данные (только ID и вероятность)
    results = []
    for i, row in df.iterrows():
        client_id = row['ID клиента']
        prob_contract = probabilities[i][1]  # вероятность заключить договор
        prob_contract_percent = round(prob_contract * 100, 1)  # в процентах с одним знаком после запятой

        results.append([
            client_id,
            f"{prob_contract_percent}%"
        ])

    # Заголовки (только два столбца)
    headers = ['ID клиента', 'Вероятность заключения договора']

    # Записываем заголовки
    results_sheet.update('A1', [headers])

    # Записываем данные
    results_sheet.update('A2', results)

    print(f"✅ Записано {len(results)} строк в лист 'Результаты'")
    print(f"   - Столбцы: {headers}")

# Функция для вывода статистики
def print_statistics(df, probabilities, accuracy):
    """Вывод статистики в консоль"""

    print("\n" + "=" * 70)
    print("СТАТИСТИКА ПО КЛИЕНТАМ")
    print("=" * 70)

    # Распределение по типам компаний
    print("\n📊 Распределение по типам компаний:")
    company_counts = df['Тип компании'].value_counts()
    for company, count in company_counts.items():
        print(f"   {company}: {count} клиентов")

    # Распределение по стадиям работы
    print("\n📊 Распределение по стадиям работы:")
    stage_counts = df['Стадия работы с клиентом'].value_counts()
    for stage, count in stage_counts.items():
        print(f"   {stage}: {count} клиентов")

    # Распределение по потребностям
    print("\n📊 Распределение по потребностям:")
    need_counts = df['Потребность клиента в товаре'].value_counts()
    for need, count in need_counts.items():
        print(f"   {need}: {count} клиентов")

    # Статистика по вероятностям
    prob_contracts = probabilities[:, 1]
    print(f"\n📈 Статистика вероятностей заключения договора:")
    print(f"   Средняя вероятность: {prob_contracts.mean():.2%}")
    print(f"   Медианная вероятность: {np.median(prob_contracts):.2%}")
    print(f"   Минимальная: {prob_contracts.min():.2%}")
    print(f"   Максимальная: {prob_contracts.max():.2%}")

    # Количество клиентов с разным статусом
    high_prob = sum(prob_contracts >= 0.7)
    medium_prob = sum((prob_contracts >= 0.4) & (prob_contracts < 0.7))
    low_prob = sum(prob_contracts < 0.4)

    print(f"\n🎯 Распределение по статусу вероятности:")
    print(f"   Высокая вероятность (≥70%): {high_prob} клиентов")
    print(f"   Средняя вероятность (40-69%): {medium_prob} клиентов")
    print(f"   Низкая вероятность (<40%): {low_prob} клиентов")

    # Точность модели
    print(f"\n🤖 Точность модели (Accuracy): {accuracy:.2%}")

    # Топ-10 клиентов с наибольшей вероятностью
    print("\n🏆 ТОП-10 клиентов с наибольшей вероятностью заключения договора:")
    df_with_prob = df.copy()
    df_with_prob['Вероятность'] = prob_contracts
    top_clients = df_with_prob.nlargest(10, 'Вероятность')[['ID клиента', 'Тип компании', 'Вероятность']]
    for _, row in top_clients.iterrows():
        print(f"   ID {int(row['ID клиента'])}: {row['Тип компании']} - {row['Вероятность']:.2%}")

